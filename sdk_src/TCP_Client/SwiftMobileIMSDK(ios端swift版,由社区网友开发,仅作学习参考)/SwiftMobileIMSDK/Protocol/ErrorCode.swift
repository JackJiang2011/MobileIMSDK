//  错误码常量表
//  建议 0~1024 范围内的错误码作为IM核心框架保留，业务层请使用 >1024 的码表示

import Foundation


enum ErrorCode: Int {
    ////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////
    /// mark - 客户端本地使用地一些通用编码约定
    ////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////
    
    /// 参数为空
    case paramError = -2
    /// 未知类型
    case unknown = -1
    
    /// 一切正常
    case commonCodeOK = 0
    /// 客户端尚未登陆
    case commonNotLogin = 1
    /// 未知错误
    case commonUnknownError = 2
    /// 数据发送失败
    case commonDataSendFail = 3
    /// 无效的对象
    case commonInvalidProtocol = 4
    
    
    ////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////
    /// mark - 由客户端产生的错误码
    ////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////

    /// 与服务端的连接已断开
    case disconnectToServer = 201
    /// 与服务端的网络连接失败
    case badDisconnectToServer = 202
    /// 客户端SDK尚未初始化
    case clientSDKNotInitial = 203
    /// 本地网络不可用（未打开）
    case localNetworkNotWorking = 204
    /// 要连接的服务端网络参数未设置
    case serverNetworkNotSetup = 205
    
    
    ////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////
    /// mark - 由服务端产生的错误码
    ////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////
    
    /// 客户端尚未登陆，请重新登陆
    case noLoginFromResponse = 301
}

